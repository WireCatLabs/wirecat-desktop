const hm = (minutes: number, h: string, min: string) => {
  const hours = Math.floor(minutes / 60)
  const rest = minutes % 60
  return [hours ? `${hours} ${h}` : "", rest || !hours ? `${rest} ${min}` : ""].filter(Boolean).join(" ")
}

